export type IconName = keyof typeof raw;

const inner = new Map<string, string>();

/** The SVG's inner markup (paths), cached. */
export function iconPaths(name: IconName): string {
  let s = inner.get(name);
  if (s === undefined) {
    const svg = raw[name] as string;
    s = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
    inner.set(name, s);
  }
  return s;
}

/** Whether a Material icon name (from the host) is bundled. */
export const hasIcon = (name: string): name is IconName => Object.prototype.hasOwnProperty.call(raw, name);
